    public function run(): void
    {
        $namaOffset = 0;

        foreach (self::TINGKAT as $tingkat) {
            foreach (self::JURUSAN as $jurusan) {
                $kelas = "{$tingkat} {$jurusan}";
                $siswaKelasIni = DB::table('siswas')
                    ->where('jurusan', $jurusan)
                    ->where(function ($query) use ($tingkat) {
                        $query->where('kelas', $tingkat)
                            ->orWhere('kelas', 'like', $tingkat.' %');
                    })
                    ->orderBy('kelas')
                    ->get(['id', 'kelas']);
                $kelasUntukSiswaBaru = $siswaKelasIni->first()->kelas ?? $kelas;
                $now = now();
                $siswaTambahan = [];

                for ($i = 0; $i < self::JUMLAH_SISWA_PER_KELAS; $i++) {
                    $studentName = self::NAMA_SISWA[$namaOffset + $i];
                    if (isset($siswaKelasIni[$i])) {
                        DB::table('siswas')->where('id', $siswaKelasIni[$i]->id)->update([
                            'name' => $studentName,
                            'updated_at' => $now,
                        ]);

                        continue;
                    }

                    $siswaTambahan[] = [
                        'name' => $studentName,
                        'kelas' => $kelasUntukSiswaBaru,
                        'jurusan' => $jurusan,
                        'alamat' => 'Alamat contoh',
                        'created_at' => $now,
                        'updated_at' => $now,
                    ];
                }

                if ($siswaTambahan !== []) {
                    DB::table('siswas')->insert($siswaTambahan);
                }
                $namaOffset += self::JUMLAH_SISWA_PER_KELAS;
            }
        }
    }
